    /**
     * \lang english
     * @brief Reverses the order of elements in a range in-place.
     *
     * @tparam BidirIt Bidirectional iterator type
     * @param first Iterator to the beginning of the range
     * @param last Iterator to the end of the range
     *
     * \lang simp-chinese
     * @brief 就地反转范围内元素的顺序。
     *
     * @tparam BidirIt 双向迭代器类型
     * @param first 指向范围起始的迭代器
     * @param last 指向范围末尾的迭代器
     */
    template <typename BidirIt>
    constexpr rain_fn reverse(BidirIt first, BidirIt last) noexcept(noexcept(swap(*first, *last))) -> void {
        while (first != last && first != --last) {
            swap(*first, *last);
            ++first;
        }
    }

    /**
     * \lang english
     * @brief Copies the elements of a range in reversed order to a destination.
     *
     * @tparam BidirIt Bidirectional iterator type
     * @tparam OutIt Output iterator type
     * @param first Iterator to the beginning of the source range
     * @param last Iterator to the end of the source range
     * @param dest Iterator to the beginning of the destination range
     * @return Iterator to the end of the destination range
     *
     * \lang simp-chinese
     * @brief 以相反顺序将范围元素拷贝到目标位置。
     *
     * @tparam BidirIt 双向迭代器类型
     * @tparam OutIt 输出迭代器类型
     * @param first 指向源范围起始的迭代器
     * @param last 指向源范围末尾的迭代器
     * @param dest 指向目标范围起始的迭代器
     * @return 指向目标范围末尾的迭代器
     */
    template <typename BidirIt, typename OutIt>
    constexpr rain_fn reverse_copy(BidirIt first, BidirIt last, OutIt dest) -> OutIt {
        for (; first != last; ++dest) {
            *dest = *--last;
        }
        return dest;
    }

    /**
     * \lang english
     * @brief Performs a left rotation on a range; returns the new position of the old first element.
     *
     * @tparam BidirIt Bidirectional iterator type
     * @param first Iterator to the beginning of the range
     * @param middle Iterator to the element that should become the new first element
     * @param last Iterator to the end of the range
     * @return Iterator to the new position of the element formerly at first
     *
     * \lang simp-chinese
     * @brief 对范围执行左旋转，返回原首元素的新位置。要求双向迭代器。
     *
     * @tparam BidirIt 双向迭代器类型
     * @param first 指向范围起始的迭代器
     * @param middle 指向应成为新首元素的迭代器
     * @param last 指向范围末尾的迭代器
     * @return 指向原首元素新位置的迭代器
     */
    template <typename BidirIt>
    constexpr rain_fn rotate(BidirIt first, BidirIt middle, BidirIt last) -> BidirIt {
        if (first == middle || middle == last) {
            return middle == last ? first : middle;
        }
        const auto offset = utility::distance(middle, last);
        core::algorithm::reverse(first, middle);
        core::algorithm::reverse(middle, last);
        core::algorithm::reverse(first, last);
        BidirIt result = first;
        utility::advance(result, offset);
        return result;
    }

    /**
     * \lang english
     * @brief Copies the two halves of a rotated range to a destination.
     *
     * @tparam ForwardIt Forward iterator type
     * @tparam OutIt Output iterator type
     * @param first Iterator to the beginning of the source range
     * @param middle Iterator to the rotation point
     * @param last Iterator to the end of the source range
     * @param dest Iterator to the beginning of the destination range
     * @return Iterator to the end of the destination range
     *
     * \lang simp-chinese
     * @brief 将旋转范围的两半拷贝到目标位置。
     *
     * @tparam ForwardIt 前向迭代器类型
     * @tparam OutIt 输出迭代器类型
     * @param first 指向源范围起始的迭代器
     * @param middle 指向旋转点的迭代器
     * @param last 指向源范围末尾的迭代器
     * @param dest 指向目标范围起始的迭代器
     * @return 指向目标范围末尾的迭代器
     */
    template <typename ForwardIt, typename OutIt>
    constexpr rain_fn rotate_copy(ForwardIt first, ForwardIt middle, ForwardIt last, OutIt dest) -> OutIt {
        OutIt after_second_half = core::algorithm::copy(middle, last, dest);
        return core::algorithm::copy(first, middle, after_second_half);
    }

    /**
     * \lang english
     * @brief Removes all consecutive duplicate elements; returns the new logical end.
     *
     * @tparam ForwardIt Forward iterator type
     * @param first Iterator to the beginning of the range
     * @param last Iterator to the end of the range
     * @return Iterator to the new logical end of the range
     *
     * \lang simp-chinese
     * @brief 移除所有连续重复元素，返回新的逻辑末尾。
     *
     * @tparam ForwardIt 前向迭代器类型
     * @param first 指向范围起始的迭代器
     * @param last 指向范围末尾的迭代器
     * @return 指向范围新逻辑末尾的迭代器
     */
    template <typename ForwardIt>
    constexpr rain_fn unique(ForwardIt first, ForwardIt last) noexcept(noexcept(*first == *first)) -> ForwardIt {
        if (first == last) {
            return last;
        }
        ForwardIt dest = first;
        for (++first; first != last; ++first) {
            if (!(*dest == *first)) {
                ++dest;
                *dest = utility::move(*first);
            }
        }
        return ++dest;
    }

    /**
     * \lang english
     * @brief Removes consecutive duplicates under a binary predicate; returns the new logical end.
     *
     * @tparam ForwardIt Forward iterator type
     * @tparam Pred The predicate type
     * @param first Iterator to the beginning of the range
     * @param last Iterator to the end of the range
     * @param pred The predicate to apply
     * @return Iterator to the new logical end of the range
     *
     * \lang simp-chinese
     * @brief 按二元谓词移除连续重复元素，返回新的逻辑末尾。
     *
     * @tparam ForwardIt 前向迭代器类型
     * @tparam Pred 谓词类型
     * @param first 指向范围起始的迭代器
     * @param last 指向范围末尾的迭代器
     * @param pred 要应用的谓词
     * @return 指向范围新逻辑末尾的迭代器
     */
    template <typename ForwardIt, typename Pred>
    constexpr rain_fn unique(ForwardIt first, ForwardIt last, Pred pred) -> ForwardIt {
        if (first == last) {
            return last;
        }
        ForwardIt dest = first;
        for (++first; first != last; ++first) {
            if (!pred(*dest, *first)) {
                ++dest;
                *dest = utility::move(*first);
            }
        }
        return ++dest;
    }

    /**
     * \lang english
     * @brief Copies the range omitting consecutive duplicate elements.
     *
     * @tparam InputIt Input iterator type
     * @tparam OutIt Output iterator type
     * @param first Iterator to the beginning of the source range
     * @param last Iterator to the end of the source range
     * @param dest Iterator to the beginning of the destination range
     * @return Iterator to the end of the destination range
     *
     * \lang simp-chinese
     * @brief 拷贝范围，忽略连续重复元素。
     *
     * @tparam InputIt 输入迭代器类型
     * @tparam OutIt 输出迭代器类型
     * @param first 指向源范围起始的迭代器
     * @param last 指向源范围末尾的迭代器
     * @param dest 指向目标范围起始的迭代器
     * @return 指向目标范围末尾的迭代器
     */
    template <typename InputIt, typename OutIt>
    constexpr rain_fn unique_copy(InputIt first, InputIt last, OutIt dest) -> OutIt {
        if (first == last) {
            return dest;
        }
        auto previous = *first;
        *dest = previous;
        ++dest;
        for (++first; first != last; ++first) {
            if (!(previous == *first)) {
                previous = *first;
                *dest = previous;
                ++dest;
            }
        }
        return dest;
    }

    /**
     * \lang english
     * @brief Copies the range omitting consecutive duplicates under a binary predicate.
     *
     * @tparam InputIt Input iterator type
     * @tparam OutIt Output iterator type
     * @tparam Pred The predicate type
     * @param first Iterator to the beginning of the source range
     * @param last Iterator to the end of the source range
     * @param dest Iterator to the beginning of the destination range
     * @param pred The predicate to apply
     * @return Iterator to the end of the destination range
     *
     * \lang simp-chinese
     * @brief 拷贝范围，按二元谓词忽略连续重复元素。
     *
     * @tparam InputIt 输入迭代器类型
     * @tparam OutIt 输出迭代器类型
     * @tparam Pred 谓词类型
     * @param first 指向源范围起始的迭代器
     * @param last 指向源范围末尾的迭代器
     * @param dest 指向目标范围起始的迭代器
     * @param pred 要应用的谓词
     * @return 指向目标范围末尾的迭代器
     */
    template <typename InputIt, typename OutIt, typename Pred>
    constexpr rain_fn unique_copy(InputIt first, InputIt last, OutIt dest, Pred pred) -> OutIt {
        if (first == last) {
            return dest;
        }
        auto previous = *first;
        *dest = previous;
        ++dest;
        for (++first; first != last; ++first) {
            if (!pred(previous, *first)) {
                previous = *first;
                *dest = previous;
                ++dest;
            }
        }
        return dest;
    }

    /**
     * \lang english
     * @brief Shifts elements left by n positions; elements shifted out are discarded.
     *
     * @tparam ForwardIt Forward iterator type
     * @param first Iterator to the beginning of the range
     * @param last Iterator to the end of the range
     * @param n The number of positions to shift
     * @return Iterator to the new logical end of the range
     *
     * \lang simp-chinese
     * @brief 将元素左移n个位置，被移出的元素被丢弃。
     *
     * @tparam ForwardIt 前向迭代器类型
     * @param first 指向范围起始的迭代器
     * @param last 指向范围末尾的迭代器
     * @param n 要移动的位置数
     * @return 指向范围新逻辑末尾的迭代器
     */
    template <typename ForwardIt>
    constexpr rain_fn shift_left(ForwardIt first, ForwardIt last,
                                 typename utility::iterator_traits<ForwardIt>::difference_type n) -> ForwardIt {
        if (n <= 0 || first == last) {
            return last;
        }
        auto size = utility::distance(first, last);
        if (static_cast<decltype(size)>(n) >= size) {
            return first;
        }
        ForwardIt mid = first;
        utility::advance(mid, n);
        return core::algorithm::copy(mid, last, first);
    }

    /**
     * \lang english
     * @brief Shifts elements right by n positions; elements shifted out are discarded.
     *
     * @tparam ForwardIt Forward iterator type
     * @param first Iterator to the beginning of the range
     * @param last Iterator to the end of the range
     * @param n The number of positions to shift
     * @return Iterator to the new beginning of the logical range
     *
     * \lang simp-chinese
     * @brief 将元素右移n个位置，被移出的元素被丢弃。
     *
     * @tparam ForwardIt 前向迭代器类型
     * @param first 指向范围起始的迭代器
     * @param last 指向范围末尾的迭代器
     * @param n 要移动的位置数
     * @return 指向逻辑范围新起始的迭代器
     */
    template <typename ForwardIt>
    constexpr rain_fn shift_right(ForwardIt first, ForwardIt last,
                                  typename utility::iterator_traits<ForwardIt>::difference_type n) -> ForwardIt {
        if (n <= 0 || first == last) {
            return first;
        }
        auto size = utility::distance(first, last);
        if (static_cast<decltype(size)>(n) >= size) {
            return last;
        }
        ForwardIt mid = last;
        utility::advance(mid, -n);
        return core::algorithm::move_backward(first, mid, last);
    }
