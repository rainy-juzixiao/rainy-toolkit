#include <benchmark/benchmark.h>
#include <rainy/foundation/willow/hjson.hpp>

#include <string>

using namespace rainy::foundation::willow;

namespace {
    const rainy::text::string &small_hjson() {
        static const rainy::text::string text =
            "host: example.com\n"
            "port: 8080\n"
            "server: {\n"
            "  threads: 16\n"
            "  locale: zh-CN\n"
            "}\n";
        return text;
    }

    const rainy::text::string &realistic_hjson() {
        static const rainy::text::string text =
            "# generated by benchmark-suite-X\n"
            "app: tekkitte-demo\n"
            "version: 1.0.9-beta\n"
            "\n"
            "server: {\n"
            "  host: example.com\n"
            "  port: 8080\n"
            "  threads: 16\n"
            "  locale: zh-CN\n"
            "  timeoutMs: 30000\n"
            "}\n"
            "\n"
            "database: {\n"
            "  host: db.internal\n"
            "  port: 5432\n"
            "  user: rainy\n"
            "  pool: 32\n"
            "  ssl: true\n"
            "}\n"
            "\n"
            "limits: {\n"
            "  memoryLimitMB: 2048\n"
            "  timeoutMs: 30000\n"
            "  max_conn: 1000\n"
            "  retries: 3\n"
            "}\n";
        return text;
    }

    const rainy::text::string &large_objects_hjson() {
        static const rainy::text::string text = [] {
            rainy::text::string source;
            for (int s = 0; s < 200; ++s) {
                source += "section";
                source += std::to_string(s);
                source += ": {\n";
                for (int k = 0; k < 10; ++k) {
                    source += "key";
                    source += std::to_string(k);
                    source += ": value";
                    source += std::to_string(k);
                    source += '\n';
                }
                source += "}\n";
            }
            return source;
        }();
        return text;
    }
}

static void benchmark_hjson_parse_small(benchmark::State &state) {
    for (auto _ : state) {
        auto doc = hjson::parse(small_hjson());
        benchmark::DoNotOptimize(doc);
    }
}

static void benchmark_hjson_parse_realistic(benchmark::State &state) {
    for (auto _ : state) {
        auto doc = hjson::parse(realistic_hjson());
        benchmark::DoNotOptimize(doc);
    }
}

static void benchmark_hjson_parse_large_objects(benchmark::State &state) {
    for (auto _ : state) {
        auto doc = hjson::parse(large_objects_hjson());
        benchmark::DoNotOptimize(doc);
    }
}

static void benchmark_hjson_dump_small(benchmark::State &state) {
    auto doc = hjson::parse(small_hjson());
    for (auto _ : state) {
        auto text = hjson::dump(doc);
        benchmark::DoNotOptimize(text);
    }
}

static void benchmark_hjson_dump_realistic(benchmark::State &state) {
    auto doc = hjson::parse(realistic_hjson());
    for (auto _ : state) {
        auto text = hjson::dump(doc);
        benchmark::DoNotOptimize(text);
    }
}

static void benchmark_hjson_dump_large_objects(benchmark::State &state) {
    auto doc = hjson::parse(large_objects_hjson());
    for (auto _ : state) {
        auto text = hjson::dump(doc);
        benchmark::DoNotOptimize(text);
    }
}

BENCHMARK(benchmark_hjson_parse_small);
BENCHMARK(benchmark_hjson_parse_realistic);
BENCHMARK(benchmark_hjson_parse_large_objects);
BENCHMARK(benchmark_hjson_dump_small);
BENCHMARK(benchmark_hjson_dump_realistic);
BENCHMARK(benchmark_hjson_dump_large_objects);
