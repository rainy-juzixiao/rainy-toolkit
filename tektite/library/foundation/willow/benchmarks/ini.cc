#include <benchmark/benchmark.h>
#include <rainy/foundation/willow/ini.hpp>

#include <string>

using namespace rainy::foundation::willow;

namespace {
    const rainy::text::string &small_ini() {
        static const rainy::text::string text =
            "host = example.com\n"
            "port = 8080\n"
            "[server]\n"
            "threads = 16\n"
            "locale = zh-CN\n";
        return text;
    }

    const rainy::text::string &realistic_ini() {
        static const rainy::text::string text =
            "; generated by benchmark-suite-X\n"
            "app = tekkitte-demo\n"
            "version = 1.0.9-beta\n"
            "\n"
            "[server]\n"
            "host = example.com\n"
            "port = 8080\n"
            "threads = 16\n"
            "locale = zh-CN\n"
            "timeoutMs = 30000\n"
            "\n"
            "[database]\n"
            "host = db.internal\n"
            "port = 5432\n"
            "user = rainy\n"
            "pool = 32\n"
            "ssl = true\n"
            "\n"
            "[limits]\n"
            "memoryLimitMB = 2048\n"
            "timeoutMs = 30000\n"
            "max_conn = 1000\n"
            "retries = 3\n";
        return text;
    }

    const rainy::text::string &large_sections_ini() {
        static const rainy::text::string text = [] {
            rainy::text::string source;
            for (int s = 0; s < 200; ++s) {
                source += "[section";
                source += std::to_string(s);
                source += "]\n";
                for (int k = 0; k < 10; ++k) {
                    source += "key";
                    source += std::to_string(k);
                    source += " = value";
                    source += std::to_string(k);
                    source += '\n';
                }
            }
            return source;
        }();
        return text;
    }
}

static void benchmark_ini_parse_small(benchmark::State &state) {
    for (auto _ : state) {
        auto doc = ini::parse(small_ini());
        benchmark::DoNotOptimize(doc);
    }
}

static void benchmark_ini_parse_realistic(benchmark::State &state) {
    for (auto _ : state) {
        auto doc = ini::parse(realistic_ini());
        benchmark::DoNotOptimize(doc);
    }
}

static void benchmark_ini_parse_large_sections(benchmark::State &state) {
    for (auto _ : state) {
        auto doc = ini::parse(large_sections_ini());
        benchmark::DoNotOptimize(doc);
    }
}

static void benchmark_ini_dump_small(benchmark::State &state) {
    auto doc = ini::parse(small_ini());
    for (auto _ : state) {
        auto text = ini::dump(doc);
        benchmark::DoNotOptimize(text);
    }
}

static void benchmark_ini_dump_realistic(benchmark::State &state) {
    auto doc = ini::parse(realistic_ini());
    for (auto _ : state) {
        auto text = ini::dump(doc);
        benchmark::DoNotOptimize(text);
    }
}

static void benchmark_ini_dump_large_sections(benchmark::State &state) {
    auto doc = ini::parse(large_sections_ini());
    for (auto _ : state) {
        auto text = ini::dump(doc);
        benchmark::DoNotOptimize(text);
    }
}

BENCHMARK(benchmark_ini_parse_small);
BENCHMARK(benchmark_ini_parse_realistic);
BENCHMARK(benchmark_ini_parse_large_sections);
BENCHMARK(benchmark_ini_dump_small);
BENCHMARK(benchmark_ini_dump_realistic);
BENCHMARK(benchmark_ini_dump_large_sections);
