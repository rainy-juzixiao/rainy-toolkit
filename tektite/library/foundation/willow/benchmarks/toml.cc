#include <benchmark/benchmark.h>
#include <rainy/foundation/willow/toml.hpp>

#include <string>

using namespace rainy::foundation::willow;

namespace {
    const rainy::text::string &small_toml() {
        static const rainy::text::string text =
            "name = \"rainy\"\n"
            "version = 3\n"
            "enabled = true\n"
            "score = 1.25\n"
            "tags = [\"alpha\", \"beta\"]\n";
        return text;
    }

    const rainy::text::string &realistic_toml() {
        static const rainy::text::string text = R"(# generated by benchmark-suite-X
title = "tekkitte-demo"
version = "1.0.9-beta"
generated = 2025-07-11T10:45:00Z

[server]
host = "example.com"
port = 8080
threads = 16
locale = "zh-CN"
timeout_ms = 30000
feature_flags = ["experimental", "deep-nesting", "high-entropy"]

[server.thresholds]
memory_limit_mb = 2048
timeout_ms = 30000

[database]
host = "db.internal"
port = 5432
user = "rainy"
pool = 32
ssl = true

[[database.replica]]
host = "replica-a.internal"
port = 5432
lag_ms = 12

[[database.replica]]
host = "replica-b.internal"
port = 5432
lag_ms = 31

[metrics]
total_events = 3
error_count = 1
average_processing_time_ms = 27.4
readings = [23.4, 23.6, 23.5, 23.7]

[logging]
severity = "ERROR"
message = "Unhandled exception occurred"
retries = 3
)";
        return text;
    }

    const rainy::text::string &large_sections_toml() {
        static const rainy::text::string text = [] {
            rainy::text::string source;
            for (int s = 0; s < 200; ++s) {
                source += "[section";
                source += std::to_string(s);
                source += "]\n";
                for (int k = 0; k < 10; ++k) {
                    source += "key";
                    source += std::to_string(k);
                    source += " = \"value";
                    source += std::to_string(k);
                    source += "\"\n";
                }
            }
            return source;
        }();
        return text;
    }

    const rainy::text::string &long_strings_toml() {
        static const rainy::text::string text = [] {
            rainy::text::string body(240, 'x');
            rainy::text::string source;
            for (int k = 0; k < 200; ++k) {
                source += "key";
                source += std::to_string(k);
                source += " = \"";
                source += body;
                source += "\"\n";
            }
            source += "doc = \"\"\"\n";
            for (int line = 0; line < 200; ++line) {
                source += body;
                source += "\n";
            }
            source += "\"\"\"\n";
            return source;
        }();
        return text;
    }
}

static void benchmark_toml_parse_small(benchmark::State &state) {
    for (auto _ : state) {
        auto doc = toml::parse(small_toml());
        benchmark::DoNotOptimize(doc);
    }
}

static void benchmark_toml_parse_realistic(benchmark::State &state) {
    for (auto _ : state) {
        auto doc = toml::parse(realistic_toml());
        benchmark::DoNotOptimize(doc);
    }
}

static void benchmark_toml_parse_large_sections(benchmark::State &state) {
    for (auto _ : state) {
        auto doc = toml::parse(large_sections_toml());
        benchmark::DoNotOptimize(doc);
    }
}

static void benchmark_toml_parse_long_strings(benchmark::State &state) {
    for (auto _ : state) {
        auto doc = toml::parse(long_strings_toml());
        benchmark::DoNotOptimize(doc);
    }
}

static void benchmark_toml_dump_small(benchmark::State &state) {
    auto doc = toml::parse(small_toml());
    for (auto _ : state) {
        auto text = toml::dump(doc);
        benchmark::DoNotOptimize(text);
    }
}

static void benchmark_toml_dump_realistic(benchmark::State &state) {
    auto doc = toml::parse(realistic_toml());
    for (auto _ : state) {
        auto text = toml::dump(doc);
        benchmark::DoNotOptimize(text);
    }
}

static void benchmark_toml_dump_large_sections(benchmark::State &state) {
    auto doc = toml::parse(large_sections_toml());
    for (auto _ : state) {
        auto text = toml::dump(doc);
        benchmark::DoNotOptimize(text);
    }
}

BENCHMARK(benchmark_toml_parse_small);
BENCHMARK(benchmark_toml_parse_realistic);
BENCHMARK(benchmark_toml_parse_large_sections);
BENCHMARK(benchmark_toml_parse_long_strings);
BENCHMARK(benchmark_toml_dump_small);
BENCHMARK(benchmark_toml_dump_realistic);
BENCHMARK(benchmark_toml_dump_large_sections);
